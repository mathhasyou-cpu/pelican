"""Доля и её интервал: одна реализация на все замеры ветки.

⚠️ **Интервал Уилсона, а не Вальда.** `p ± 1.96·√(p(1−p)/n)` на долях 0 и 1
вырождается в ноль ширины, и «0 ложных из 30» читалось бы как «ложных не бывает».
Уилсон даёт честную верхнюю границу ~11% (Wilson 1927; Brown, Cai & DasGupta 2001).

⚠️ Интервал печатается ВСЕГДА рядом с долей: на 70 позициях ТОП он около ±0.11, и
разница меньше него между двумя версиями результатом не является.
"""

from __future__ import annotations


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95% интервал Уилсона для доли k/n."""
    if n == 0:
        return 0.0, 1.0
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / denom
    return max(0.0, centre - half), min(1.0, centre + half)


def span(k: int, n: int) -> str:
    """Интервал строкой, как он печатается в отчётах: `[0.86; 0.97]`."""
    lo, hi = wilson(k, n)
    return f"[{lo:.2f}; {hi:.2f}]"
