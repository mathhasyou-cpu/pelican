"""Жанр зрелости технологии: что из найденного вообще идёт в выдачу.

## Почему категориальный класс, а не порог по числу

Замер ветки болей ([kind](../../docs/kind.md), `src/trends_anal/kinds.py`):
**ни одна посчитанная ось не разделяла** оценки человека (AUC 0.38–0.53 по семи
осям), а категориальный жанр от модели поднял долю годного в верху выдачи с 29%
до 61%. Правило проекта прямое: если классы не разделяются по числу, ось не та,
и задача уходит на модель. Здесь ровно такой случай: «зрелое» и «зарождающееся»
на одном счёте публикаций не расходятся, потому что зрелое тоже публикуют.

## Словарь — дословно список исключений ТЗ

ТЗ перечисляет, что НЕ должно попасть в выдачу: «зрелые тренды, массово
используемые технологии, отраслевые стандарты, технологии со сформированным
рынком, выраженными лидерами и устойчивым конкурентным разделением, а также
маркетинговый хайп и информационный шум». Каждое — свой класс, и причина
исключения показывается в интерфейсе тем же словом, каким её назвало ТЗ.

⚠️ **Порядок классов — часть промпта.** Модель берёт первый подошедший, поэтому
исключающие классы идут РАНЬШЕ `emerging`: класс, вставленный перед ним, отнимает
только у него и не трогает остальные (тот же приём, что в `kinds.py` ветки болей).

⚠️ **Отсев считается вслух.** Молчащий пробел читался бы как «таких не нашлось»:
жюри отдельно оценивает «логику исключения зрелых трендов», и её надо показать.
"""

from __future__ import annotations

TOO_BROAD = "too_broad"
NOISE = "noise"
HYPE = "hype"
STANDARD = "standard"
MATURE = "mature"
EMERGING = "emerging"

#: Порядок проверки = порядок в промпте. `emerging` последний: ему достаётся то,
#: что не подошло ни под одно исключение.
KINDS = (TOO_BROAD, NOISE, HYPE, STANDARD, MATURE, EMERGING)

#: Что идёт в выдачу. Остальное прячется и считается вслух.
SHOWN = (EMERGING,)

LABELS = {
    EMERGING: "зарождающаяся технология",
    MATURE: "зрелая: массовое внедрение, сформированный рынок, выраженные лидеры",
    STANDARD: "отраслевой стандарт или спецификация",
    HYPE: "маркетинговый хайп без технического содержания",
    NOISE: "информационный шум: не технология",
    TOO_BROAD: "слишком общая категория, а не технология",
}


def label_of(kind: str) -> str:
    return LABELS.get(kind, kind)
