"""Рубрика методологов: балл слабого сигнала — это сумма двух порядковых шкал.

## Замер: рубрика воспроизводится, и словарь у неё закрытый

Датасет организаторов (100 строк, `scripts/weak_signals_100.tsv`) несёт колонку
«Балл (стадия+тренд)» со значениями 3..7. Шапка не врёт — балл **буквально
аддитивный**, и обе шкалы восстанавливаются по самим данным:

| стадия | ранг |   | тренд | ранг |
|---|---|---|---|---|
| Концепция/Исследование | 1 |  | Растёт | 2 |
| Прототип/PoC | 2 |  | Растёт быстро | 3 |
| Пилот | 3 |  | | |
| Раннее внедрение | 4 |  | | |

**Сходится 98 строк из 100, расходится НИ ОДНОЙ.** Оставшиеся две не
выражаются закрытым словарём вовсе: строка 93 называет стадией «Ранние внедрения
(ограниченный институциональный доступ)», а считает её как прототип; строка 99
несёт третью формулировку тренда («Стабильный с ускорением»). То есть внутри
того, что шкала вообще способна выразить, воспроизведение точное.

⚠️ **Эти две не подгоняются, и это принципиально.** Правило, дотянутое до сотни
из ста на двух наблюдениях, — не правило, а запоминание выборки. Разбор остатка
лежит здесь же, чтобы через месяц никто не «чинил» его снова.

## Два правила разбора, которые видно только по остаткам

⚠️ **Гибрид «A → B» считается по ПОЗДНЕЙ ступени.** «Пилот → Раннее внедрение»
при быстром росте даёт 7, а не 6. Наивное «берём первую названную стадию»
промахивается на 35 строках из 99 — это и был первый вариант разбора.

⚠️ **Прозаическая оговорка ступень НЕ повышает.** «Прототип/PoC → первые
поставки», «→ ранняя серия», «→ первые полисы» считаются как прототип (2), а не
как раннее внедрение (4). Ступеней ровно четыре, и они канонические; всё
остальное в колонке — пояснение, а не шкала. Без этого правила промах на 9
строках, причём ровно на две единицы.

⚠️ **«Концепция/Исследование» — ОДНА нижняя ступень, а не две.** Соблазн дать
«исследованию» ранг 2 (рядом с прототипом) промахивается на всех семи таких
строках ровно на единицу.

## Зачем это в коде

Отсюда форма выдачи модели: предсказывается **не своя шкала, а их два
порядковых поля**, и балл собирается сложением. Тогда метрика считается на языке
заказчика, а требование ТЗ «показать, по каким именно признакам» распадается на
два понятных вопроса — почему такая стадия и почему такой тренд.

⚠️ У рубрики **ноль подгоняемых параметров**, поэтому переобучиться на ста
строках ей нечем, и проверяется она на всех ста без единого выдуманного
отрицательного примера. Это самое крепкое число, какое у нас есть про часть 1
(`docs/weak-signals.md`).
"""

from __future__ import annotations

import re

CONCEPT = "концепция/исследование"
PROTOTYPE = "прототип/poc"
PILOT = "пилот"
EARLY = "раннее внедрение"

#: Порядок — это и есть шкала: индекс + 1 равен рангу.
STAGES = (CONCEPT, PROTOTYPE, PILOT, EARLY)

GROWING = "растёт"
FAST = "растёт быстро"
TRENDS = (GROWING, FAST)

STAGE_RANK = {name: i + 1 for i, name in enumerate(STAGES)}
TREND_RANK = {GROWING: 2, FAST: 3}

STAGE_LABELS = {
    CONCEPT: "Концепция/Исследование",
    PROTOTYPE: "Прототип/PoC",
    PILOT: "Пилот",
    EARLY: "Раннее внедрение",
}
TREND_LABELS = {GROWING: "Растёт", FAST: "Растёт быстро"}

#: ⚠️ Только канонические ступени. «Ранние поставки», «первые интеграции» и
#: прочая проза сюда не входят НАМЕРЕННО — см. докстринг модуля.
_STAGE_PATTERNS = (
    (re.compile(r"концепц|исследован"), CONCEPT),
    (re.compile(r"прототип|poc"), PROTOTYPE),
    (re.compile(r"пилот"), PILOT),
    (re.compile(r"раннее внедрен|раннего внедрен"), EARLY),
)


#: Атомарные чтения оценки (`assess.JUDGMENTS`), которые по определению в промпте и есть
#: ступень: «pilot, field trial» = пилот, «products on sale, paying customers» = раннее
#: внедрение. Раунд сюда не входит: деньги на прототип — не внедрение.
_STAGE_FLOORS = (("commercial_deployment", EARLY), ("pilot_mentioned", PILOT))


def stage_floor(stage: str, judgments: dict[str, float]) -> str:
    """Ступень не ниже той, что модель сама прочла в свидетельствах (consistency check).

    Одна и та же оценка иногда пишет «концепция» и тут же «есть продажи» — так OneStep
    с раундом $36M и продажами показывался зарождающимся. Противоречие решается в
    сторону прочитанного факта. ⚠️ Применяется ПОСЛЕ скоринга: `stage` — признак модели
    (`llm_features`), и менять вход обученной модели без замера нельзя.
    """
    rank = STAGE_RANK.get(stage, 0)
    for key, floor in _STAGE_FLOORS:
        if judgments.get(key) and STAGE_RANK[floor] > rank:
            stage, rank = floor, STAGE_RANK[floor]
    return stage


def parse_stage(text: str) -> str | None:
    """Ступень из записи методолога. Гибрид «A → B» — по поздней ступени."""
    low = text.lower()
    hits = [name for pattern, name in _STAGE_PATTERNS if pattern.search(low)]
    return max(hits, key=lambda n: STAGE_RANK[n]) if hits else None


def parse_trend(text: str) -> str | None:
    """Тренд из записи методолога. Третьей формулировки в шкале нет."""
    low = text.lower().strip()
    if low.startswith(("растёт быстро", "растет быстро")):
        return FAST
    if low.startswith(("растёт", "растет", "стабильный/растёт", "стабильный/растет")):
        return GROWING
    return None


def score(stage: str, trend: str) -> int:
    """Балл 3..7. Ровно то, что написано в шапке колонки: стадия плюс тренд."""
    if stage not in STAGE_RANK:
        raise ValueError(f"неизвестная стадия {stage!r}; ожидалась одна из {STAGES}")
    if trend not in TREND_RANK:
        raise ValueError(f"неизвестный тренд {trend!r}; ожидался один из {TRENDS}")
    return STAGE_RANK[stage] + TREND_RANK[trend]


def explain(stage: str, trend: str) -> str:
    """Человекочитаемая арифметика балла — она же объяснение для карточки."""
    return (
        f"{STAGE_LABELS[stage]} ({STAGE_RANK[stage]}) + "
        f"{TREND_LABELS[trend]} ({TREND_RANK[trend]}) = {score(stage, trend)}"
    )
