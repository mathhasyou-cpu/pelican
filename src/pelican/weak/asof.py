"""Срез времени: прогон на состоянии мира двухлетней давности.

Ретроспективный бэктест — единственное доказательство того, что система смотрит вперёд,
а не описывает уже случившееся: детектор гоняется на срезе, а верх его выдачи сверяется
с тем, что к сегодняшнему дню действительно взлетело.

Приём называется **point-in-time correctness**, а беда, от которой он защищает, —
**look-ahead bias** (в машинном обучении — темпоральная утечка): решение, принятое на
данных, которых на ту дату ещё не существовало, меряет не предсказание, а память.

⚠️ **Чего point-in-time не снимает — survivorship bias**: сегодняшний индекс новостей
знает только то, что дожило. Заметка, снятая с сайта за два года, в срез не попадёт, и
прошлое в нём выглядит чище, чем было.

⚠️ **Срез — глобальное состояние процесса, а не параметр вызова.** Он обязан попасть во
ВСЕ четыре двери разом (новости, привязка к корпусу, след корпуса, отсчёт свежести), и
протаскивать дату через пять слоёв значило бы однажды забыть одну из них — а забытая
дверь не ломает прогон, она молча показывает будущее. Приём тот же, что у `cache.ENABLED`.

⚠️ **Новостной поиск отыгрывается назад** — проверено: `after:`/`before:` в Google News
RSS работают, и запрос «AI agent identity startup after:2024-06-01 before:2024-09-15»
отдаёт 35 заметок, все внутри окна. Поэтому в бэктесте участвует и денежный поток, а не
одна наука.

⚠️ **Чего срез НЕ чинит**: источник, у которого нет параметра даты (Хабр, КиберЛенинка),
отдаёт сегодняшнюю страницу, и лишнее с неё отбрасывается ПОСЛЕ выдачи. Что вытеснено за
первую страницу, назад не вернуть, поэтому по этим источникам срез беднее настоящего
прошлого — и читать их вклад в бэктесте надо как нижнюю оценку.
"""

from __future__ import annotations

from datetime import date, timedelta

#: Дата среза или `None` — «сегодня». Ставится один раз на процесс.
AS_OF: date | None = None

#: Сколько истории показывать новостному поиску до среза. То же окно, что у живого
#: прогона (`when:2y`), иначе срез видел бы меньше, чем видит продукт.
WINDOW_DAYS = 730


def active() -> bool:
    return AS_OF is not None


def today() -> date:
    """«Сегодня» этого прогона: под срезом — дата среза."""
    return AS_OF or date.today()


def news_window() -> str:
    """Хвост новостного запроса: окно продукта или окно среза."""
    if AS_OF is None:
        # ⚠️ Без окна верх занимают старые громкие заметки.
        return "when:2y"
    start = AS_OF - timedelta(days=WINDOW_DAYS)
    return f"after:{start.isoformat()} before:{AS_OF.isoformat()}"


def too_late(published: str) -> bool:
    """Свидетельство из будущего относительно среза: в прогон оно не идёт."""
    if AS_OF is None or not published:
        return False
    try:
        return date.fromisoformat(published[:10]) > AS_OF
    except ValueError:
        # Дату не разобрали — свидетельство остаётся: выбрасывать по догадке нельзя.
        return False


def key(prefix: str) -> str:
    """Приставка к ключу кэша. ⚠️ Без неё срез отравил бы кэш обычных прогонов."""
    return prefix if AS_OF is None else f"{AS_OF.isoformat()}:{prefix}"
